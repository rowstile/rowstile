class Refused(Exception):
    """The database refused a write (SQLSTATE 42501): its message, the table and command, and why (lines)."""

    def __init__(self, message: str, table: str | None = None, command: str | None = None, why: Sequence[str] = ()) -> None:
        super().__init__(message)
        self.message, self.table, self.command, self.why = message, table, command, list(why)


class NotFound(Exception):
    """The row isn't there, or the signed-in user can't see it."""

    def __init__(self, table: str, id_: str) -> None:
        super().__init__(f"{{table}} {{id_}} not found")
        self.table, self.id = table, id_


def refusal(error: BaseException) -> Refused | None:
    """A Refused for a database error that is a refusal, else None (psycopg, psycopg2)."""
    if (getattr(error, "sqlstate", None) or getattr(error, "pgcode", None)) != "42501":
        return None
    diag = getattr(error, "diag", None)
    message = getattr(diag, "message_primary", None) or str(error).split("\\n")[0]
    detail = getattr(diag, "message_detail", None) or ""
    schema, table = getattr(diag, "schema_name", None), getattr(diag, "table_name", None)
    constraint = getattr(diag, "constraint_name", None) or ""
    return Refused(message, f"{{schema}}.{{table}}" if schema and table else table,
                   constraint[6:] if constraint.startswith("authz_") else None, detail.split("\\n") if detail else [])


class Authz:
    def __init__(self, conn: Connection) -> None:
        self.conn = conn

    def _one(self, sql: LiteralString, args: Sequence[object]) -> object:
        with self.conn.cursor() as cur:
            cur.execute(sql, args)
            row = cur.fetchone()
            return row[0] if row else None

    def _all(self, sql: LiteralString, args: Sequence[object]) -> Sequence[str]:
        with self.conn.cursor() as cur:
            cur.execute(sql, args)
            return [str(r[0]) for r in cur.fetchall()]

    def _rows(self, sql: LiteralString, args: Sequence[object]) -> Sequence[Row]:
        with self.conn.cursor() as cur:
            cur.execute(sql, args)
            names = [str(d[0]) for d in cur.description or []]
            return [dict(zip(names, r, strict=True)) for r in cur.fetchall()]

    @staticmethod
    def _check(type_: str, perm: str) -> None:
        if type_ not in PERMISSIONS or perm not in PERMISSIONS[type_]:
            raise ValueError(f"{{type_}} has no permission {{perm!r}} in the policy")

    def sign_in(self, user_id: Id | None) -> None:
        """For this transaction only (run inside a transaction); None: nobody. A signed session (authz.act_as)."""
        self._one("SELECT authz.act_as('user', %s)", (None if user_id is None else _id(user_id),))

    def sign_in_as(self, principal_type: str, principal_id: Id) -> None:
        """A principal other than a user (a service), for this transaction only."""
        self._one("SELECT authz.act_as(%s, %s)", (principal_type, _id(principal_id)))

    def connection_check(self) -> Sequence[Row]:
        """What is wrong with this connection, as rows of severity and problem: call it when the app starts, and
        refuse to start on an 'error' (a role row-level security doesn't apply to, or one the policy doesn't govern)."""
        return self._rows("SELECT severity, problem FROM authz.connection_check()", ())

    def principal(self) -> tuple[str, str] | None:
        """(type, id) of whoever is signed in, or None."""
        rows = self._all("SELECT principal_type || ':' || principal_id FROM authz.principal()", ())
        if not rows:
            return None
        kind, _, pid = rows[0].partition(":")
        return kind, pid

    def login_key(self, key: str) -> None:
        self._one("SELECT authz.login_key(%s)", (key,))

    def login_jwt(self, token: str) -> None:
        self._one("SELECT authz.login_jwt(%s)", (token,))

    def create_api_key(self, name: str, scopes: str = "", expires_at: When | None = None, principal_type: str | None = None,
                       principal_id: Id | None = None) -> str:
        """A key for yourself, or (holding manage_keys on it) for a principal such as a service. Shown once."""
        return str(self._one("SELECT authz.create_api_key(%s, %s, %s, %s, %s)",
                             (name, scopes, expires_at, principal_type, None if principal_id is None else _id(principal_id))))

    def list_api_keys(self, principal_type: str | None = None, principal_id: Id | None = None) -> Sequence[Row]:
        return self._rows("SELECT * FROM authz.list_api_keys(%s, %s)",
                          (principal_type, None if principal_id is None else _id(principal_id)))

    def revoke_api_key(self, key_id: int) -> None:
        self._one("SELECT authz.revoke_api_key(%s)", (key_id,))

    def can(self, type_: ObjectType, id_: Id, perm: Permission) -> bool:
        self._check(type_, perm)
        return bool(self._one("SELECT authz.can(%s, %s::text, %s)", (type_, _id(id_), perm)))

    def list(self, type_: ObjectType, perm: Permission, after: Id | None = None,
             limit: int | None = None) -> Sequence[str]:
        """Every id the user holds perm on; with limit, a page in key order after `after`."""
        self._check(type_, perm)
        return self._all("SELECT x FROM authz.list(%s, %s, %s, %s) x",
                         (type_, perm, None if after is None else _id(after), limit))

    def perms(self, type_: ObjectType, id_: Id) -> Sequence[str]:
        return _texts(self._one("SELECT authz.perms(%s, %s::text)", (type_, _id(id_))))

    def who(self, type_: ObjectType, id_: Id, perm: Permission) -> Sequence[str]:
        self._check(type_, perm)
