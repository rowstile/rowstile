    def _client_go(self, perms: Perms, source_name: str) -> str:
        """For apps on the Go SDK (github.com/rowstile/rowstile/sdk/go): the policy's types, and each type's
        permissions as a type of their own, which the SDK's calls take. A misspelled name doesn't build, and
        neither does a plain string where the SDK wants a permission. Names in Go's spelling: note's edit is
        NoteEdit, of the type NotePermission; two names that would be spelled the same get neither."""

        def go(*parts: str) -> str:  # org_unit and orgUnit: OrgUnit
            return "".join(w[:1].upper() + w[1:] for p in parts for w in p.split("_"))

        names: dict[str, list[str]] = {}  # a Go name: what it would stand for
        for t, ps in perms.items():
            names.setdefault("Type" + go(t), []).append(t)
            names.setdefault(go(t) + "Permission", []).append(t)
            for p in ps:
                names.setdefault(go(t, p), []).append(f"{t}.{p}")
