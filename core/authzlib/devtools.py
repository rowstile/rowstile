class Cursor(Protocol):
    """What the client uses of a DB-API cursor (psycopg's, psycopg2's)."""
    @property
    def description(self) -> Sequence[Sequence[object]] | None: ...
    def execute(self, query: LiteralString, params: Sequence[object], /) -> object: ...
    def fetchone(self) -> Sequence[object] | None: ...
    def fetchall(self) -> Sequence[Sequence[object]]: ...
    def __enter__(self) -> Cursor: ...
    def __exit__(self, exc_type: type[BaseException] | None, exc: BaseException | None,
                 tb: TracebackType | None, /) -> object: ...


class Connection(Protocol):
    def cursor(self) -> Cursor: ...


def _texts(value: object) -> list[str]:
    """A text[] from the database (None: none)."""
    return [str(x) for x in value] if isinstance(value, (list, tuple)) else []


def _int(value: object) -> int:
    if isinstance(value, (int, str)):
        return int(value)
    raise TypeError(f"expected a number from the database, got {{value!r}}")


def _id(x: Id) -> str:
    """A composite key as Postgres writes a row: every field quoted, quotes and backslashes escaped."""
    if isinstance(x, (tuple, list)):
        return "(" + ",".join('"' + str(v).replace("\\\\", "\\\\\\\\").replace('"', '\\\\"') + '"' for v in x) + ")"
    return str(x)


def _shown(x: Id) -> str:
    """A key as the database writes it, for a message: 7, or (1,2) for a key of several columns."""
    if not isinstance(x, (tuple, list)):
        return str(x)

    def field(v: object) -> str:
        s = str(v)
        if s == "" or any(ch in s for ch in '",\\\\()') or any(ch.isspace() for ch in s):
            return '"' + s.replace("\\\\", "\\\\\\\\").replace('"', '""') + '"'
        return s

    return "(" + ",".join(field(v) for v in x) + ")"


