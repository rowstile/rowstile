"""Policy changes as migrations.

A migration takes a database from the policy the lock file recorded to the policy now. The compiled
policy is read back as objects (statements.py): each function, view, trigger, row-level security
policy and table, with a hash of its SQL. The lock file (authz/policy.lock, committed next to the
migrations) lists them, one sorted line each, after the policy's own lines. So the next migration holds
only what changed:

- a function whose arguments and result are the same: CREATE OR REPLACE, in place
- a view that changed, or reads something that is made again: emptied in place first (the same columns, reading
  nothing), then defined again with CREATE OR REPLACE VIEW, so what the app built on it (a view over a masked
  view) stays
- a table whose columns are the same: its rows written again
- anything else that changed or went: dropped first, with everything that needs it, then made again
- an inheritance tree whose definition is the same is not touched; one that changed is rebuilt
- steps (the base tables, checks, sweeps) run when their SQL changed, some (grants) every time

A new version of rowstile is a migration only when it makes something different: the lock holds a hash of
the steps every migration runs, beside everything else, and not the version it was written by.

The first migration, with no lock, is the whole compiled policy, which also applies over a database
that already has a policy. Each migration checks that the database is where the lock said (the lock's
hash is recorded in authz.policy_versions), and records the policy it leaves in force.
"""

