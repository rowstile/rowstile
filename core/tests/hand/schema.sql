-- The tables the hand-answered policies of tests/hand/ govern: each policy takes what it needs, and its named tests
-- bring the rows (tests/hand_answers.sh applies each to a database of its own made from this file).
SET client_min_messages = warning;
DO $$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'app_user') THEN
    CREATE ROLE app_user NOLOGIN;
  END IF;
END $$;
CREATE SCHEMA app;
CREATE TABLE app.users (id bigint PRIMARY KEY, name text, active boolean NOT NULL DEFAULT true, manager_id bigint);
CREATE TABLE app.services (id bigint PRIMARY KEY, name text);
CREATE TABLE app.orgs (id bigint PRIMARY KEY);
CREATE TABLE app.org_admins (org_id bigint NOT NULL, user_id bigint NOT NULL, PRIMARY KEY (org_id, user_id));
CREATE TABLE app.org_members (org_id bigint NOT NULL, user_id bigint NOT NULL, PRIMARY KEY (org_id, user_id));
CREATE TABLE app.teams (id bigint PRIMARY KEY, parent_id bigint);
-- a team's members, and the teams inside a team by the rows of a link table that are active
CREATE TABLE app.team_members (team_id bigint NOT NULL, user_id bigint NOT NULL);
CREATE TABLE app.team_teams (team_id bigint NOT NULL, sub_id bigint NOT NULL, active boolean);
CREATE TABLE app.projects (id bigint PRIMARY KEY, owner_id bigint, public boolean NOT NULL DEFAULT false);
CREATE TABLE app.memberships (
  id bigint PRIMARY KEY, project_id bigint NOT NULL, user_id bigint NOT NULL, revoked boolean NOT NULL DEFAULT false);
CREATE TABLE app.backings (project_id bigint NOT NULL, backer_type text NOT NULL, backer_id bigint NOT NULL);
CREATE TABLE app.folders (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id      bigint,
  parent_type text,
  parent_id   bigint,
  owner_id    bigint,
  editor_id   bigint,
  name        text NOT NULL DEFAULT 'f',
  archived    boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now());
CREATE TABLE app.folder_viewers (folder_id bigint NOT NULL, user_id bigint NOT NULL, PRIMARY KEY (folder_id, user_id));
CREATE TABLE app.files (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folder_id bigint,
  project_id bigint,
  owner_id  bigint,
  name      text NOT NULL DEFAULT 'a',
  body      text);
CREATE TABLE app.file_viewers (file_id bigint NOT NULL, user_id bigint NOT NULL, PRIMARY KEY (file_id, user_id));
-- a key of two columns
CREATE TABLE app.org_folders (
  org_id bigint NOT NULL, id bigint NOT NULL, parent_id bigint, owner_id bigint, PRIMARY KEY (org_id, id));
-- a mark on a row of some kind (ref_id), or for a subject (subject_id): conditions read it in subqueries
CREATE TABLE app.marks (id bigint PRIMARY KEY, ref_id bigint, kind text NOT NULL, subject_id text);
-- documents: a parent in a column (up) or a link table, a project in a column or a link table whose row says
-- whether it is active, and the projects' own documents
CREATE TABLE app.docs (
  id bigint PRIMARY KEY, owner_id bigint, up bigint, project_id bigint, locked boolean NOT NULL DEFAULT false);
CREATE TABLE app.doc_links (child bigint NOT NULL, parent bigint NOT NULL);
CREATE TABLE app.doc_projects (doc_id bigint NOT NULL, project_id bigint NOT NULL, active boolean NOT NULL DEFAULT true);
CREATE TABLE app.project_docs (project_id bigint NOT NULL, doc_id bigint NOT NULL);
-- keys that are text
CREATE TABLE app.text_users (id text PRIMARY KEY);
CREATE TABLE app.text_docs (id text PRIMARY KEY, owner_id text, parent_id text);
-- objects of two types keyed by two columns, which a link table names by a type column and both
CREATE TABLE app.spaces (org_id bigint NOT NULL, id bigint NOT NULL, keeper_id bigint, PRIMARY KEY (org_id, id));
CREATE TABLE app.rooms (org_id bigint NOT NULL, id bigint NOT NULL, keeper_id bigint, PRIMARY KEY (org_id, id));
CREATE TABLE app.pins (doc_id bigint NOT NULL, kind text NOT NULL, org_id bigint NOT NULL, ref_id bigint NOT NULL);
GRANT USAGE ON SCHEMA app TO app_user;
GRANT SELECT ON ALL TABLES IN SCHEMA app TO app_user;
GRANT INSERT, UPDATE, DELETE ON app.folders, app.files TO app_user;
GRANT UPDATE ON app.users TO app_user;   -- (no DELETE on app.users: a write the app role has no privilege for)
GRANT USAGE ON ALL SEQUENCES IN SCHEMA app TO app_user;
