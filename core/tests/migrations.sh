#!/bin/bash
# migrations.sh: policy changes as migrations: rowstile migrate writes them for each tool, they
# apply in order on a database, a migration applied out of order is refused, --check tells CI about
# changes no migration has, and rowstile push brings a development database along the same way.
#   PGHOST=... PGUSER=authz_owner PGSUPERUSER=postgres tests/migrations.sh
set -u
cd "$(dirname "$0")/.."
DB=authz_migrations
fails=0
ok() { echo "ok    $1"; }
bad() { echo "FAIL  $1${2:+: $2}"; fails=$((fails + 1)); }
PSQL() { psql -X -q -At -v ON_ERROR_STOP=1 -d "$DB" "$@"; }
fresh() { dropdb --if-exists "$1" 2>/dev/null; createdb "$1" || exit 1
  PGOPTIONS="-c client_min_messages=error" psql -X -q -v ON_ERROR_STOP=1 -d "$1" -f example/app_schema.sql >/dev/null || exit 1; }
T=$(mktemp -d)
. tests/races.sh
# whatever way the suite ends: the sessions it left running, its databases, its files
cleanup() {
  stop_sessions
  for db in "$DB" "${DB}_2" "${DB}_3" "${DB}_4" "${DB}_5" "${DB}_6" "${DB}_7" "${DB}_8" "${DB}_9"; do dropdb --force --if-exists "$db" 2>/dev/null; done
  rm -rf "$T"
}
trap cleanup EXIT
P="$T/p"
mkdir -p "$P/db"
sed '/^test$/,$d' example/docs.authz > "$P/db/policy.authz"     # without its test section: the checks below change the policy
printf 'policy = "db/policy.authz"\ndatabase = "dbname=%s"\n[migrations]\ntool = "sql"\ndir = "db/migrations"\n' "$DB" > "$P/rowstile.toml"
CLI() { ( cd "$P" && python3 "$OLDPWD/cli/rowstile_cli.py" "$@" ); }
# every migration in the folder not applied yet, in order, each in its own transaction (as the tools do)
migrate_db() {
  local db=$1 dir=$2 done_file="$T/applied_$1"
  touch "$done_file"
  for f in $(ls "$dir"/*.sql | sort); do
    grep -qx "$f" "$done_file" && continue
    out=$(PGOPTIONS="-c client_min_messages=error" psql -X -q -1 -v ON_ERROR_STOP=1 -d "$db" -f "$f" 2>&1) || { echo "$out"; return 1; }
    echo "$f" >> "$done_file"
  done
}

echo "-- the first migration, and the lock file"
fresh "$DB"
out=$(CLI migrate 2>&1); rc=$?
[ $rc -eq 0 ] && [ -f "$P/db/policy.lock" ] && [ "$(ls "$P/db/migrations" | wc -l)" = 1 ] &&
  ok "rowstile migrate writes the first migration and db/policy.lock, with no database" || bad "first migrate" "$out"
first=$(ls "$P"/db/migrations/*.sql)
grep -q "^-- the whole policy" "$first" && ok "... which says it is the whole policy" || bad "first summary" "$(head -3 "$first")"
case "$(head -n 2 "$first")" in "-- rowstile "*": "*". Generated by rowstile migrate from the policy; don't edit it,
-- change the policy and write the next migration.") ok "... and, first, not to edit it: change the policy and write the next one";;
  *) bad "first header" "$(head -n 2 "$first")";; esac
out=$(migrate_db "$DB" "$P/db/migrations") && [ "$(PSQL -c "SELECT authz.verify()")" = t ] &&
  ok "it applies on a database with nothing of rowstile's" || bad "first applies" "$out"
[ "$(PSQL -c "SELECT lock IS NOT NULL AND policy LIKE '%type folder = app.folders%' FROM authz.policy_versions ORDER BY id DESC LIMIT 1")" = t ] &&
  ok "... and records the policy and the lock's hash" || bad "recorded"
out=$(CLI migrate 2>&1); case "$out" in "nothing to migrate"*) ok "again: nothing to migrate";; *) bad "migrate again" "$out";; esac
out=$(CLI migrate --check 2>&1); rc=$?; [ $rc -eq 0 ] && ok "--check: exit 0 when the lock is up to date" || bad "--check up to date" "$out"
# a lock another version wrote: upgrading rowstile is no migration while it makes the same
cp "$P/db/policy.lock" "$T/lock"
sed -i '1s/^# rowstile [^:]*:/# rowstile 0.0.1:/' "$P/db/policy.lock"
out=$(CLI migrate --check 2>&1); rc=$?; [ $rc -eq 0 ] && ok "--check: exit 0 after an upgrade that makes the same" || bad "--check after an upgrade" "$out"
# the other way round: an older command doesn't write the step back as if it were an upgrade
sed -i '1s/^# rowstile [^:]*:/# rowstile 99.0.0:/' "$P/db/policy.lock"
for args in "migrate --check" "migrate"; do
  out=$(CLI $args 2>&1); rc=$?
  case "$out" in *"the lock file was last written by rowstile 99.0.0, which is newer than this command"*"back [AZ616]
HINT: upgrade the rowstile command; to go back to this version on purpose, add --downgrade") [ $rc -ne 0 ] &&
    [ "$(ls "$P/db/migrations" | wc -l)" = 1 ] && ok "$args: a lock a newer version wrote is refused, with the way back" || bad "$args on a newer lock: rc $rc";;
    *) bad "$args on a newer lock" "$out";; esac
done
out=$(CLI migrate --check --downgrade 2>&1); rc=$?; [ $rc -eq 0 ] && ok "... unless asked: --downgrade" || bad "--downgrade" "$out"
# a newer version may write words this one doesn't know on an object's line: they are left aside
sed -i '/^function /s/$/ someday=1/' "$P/db/policy.lock"
out=$(CLI migrate --check --downgrade 2>&1); rc=$?
[ $rc -eq 0 ] && grep -q ' someday=1$' "$P/db/policy.lock" && ok "... which leaves aside the words it doesn't know on the lock's lines" ||
  bad "words a newer lock has" "$out"
cp "$T/lock" "$P/db/policy.lock"
grep -q '^> type folder: can edit = share or editor or (parent.edit and {inherit})$' "$P/db/policy.lock" &&
  ok "the lock file starts with the policy's lines" || bad "lock meaning" "$(head -12 "$P/db/policy.lock")"
# two branches that each wrote a migration, merged with the conflict markers left in the lock file: refused, the line
# and what to do said, nothing written
sed -i '3i<<<<<<< HEAD' "$P/db/policy.lock"
for args in "migrate --check" "migrate"; do
  out=$(CLI $args 2>&1); rc=$?
  case "$out" in *"line 3 of the lock file isn't one rowstile migrate writes (<<<<<<< HEAD): a merge"*"[AZ619]") [ $rc -eq 1 ] &&
    [ "$(ls "$P/db/migrations" | wc -l)" = 1 ] && [ "$(sed 3d "$P/db/policy.lock")" = "$(cat "$T/lock")" ] &&
    ok "$args: a lock file a merge left its conflict markers in: refused with the line, exit 1" || bad "$args on a merged lock: exit $rc";;
    *) bad "$args on a merged lock" "$out";; esac
done
cp "$T/lock" "$P/db/policy.lock"

echo "-- a change"
sed -i 's/^  can share = owner or folder.share$/  can share = owner or folder.share\n  can comment = folder.view/' "$P/db/policy.authz"
out=$(CLI migrate --check 2>&1); rc=$?
case "$out" in *"has changes no migration has"*"+ type file: can comment = folder.view"*) [ $rc -eq 1 ] && ok "--check: exit 1, and what changed" || bad "--check exit" "$rc";;
  *) bad "--check" "$out";; esac
out=$(CLI migrate 2>&1); rc=$?
second=$(ls "$P"/db/migrations/*.sql | sort | tail -n 1)
[ $rc -eq 0 ] && [ "$second" != "$first" ] && case "$second" in *_file_comment_folder_view.sql) true;; *) false;; esac &&
  ok "the next migration is named after what changed" || bad "second migrate" "$out $second"
[ "$(wc -c < "$second")" -lt 70000 ] && ! grep -q "CREATE TABLE authz_int.\"folder__parent__tree\"" "$second" &&
  ok "... and holds only what changed ($(( $(wc -c < "$second") / 1024 )) KB; no tree)" || bad "second size" "$(wc -c < "$second")"
grep -q "^-- + type file: can comment = folder.view$" "$second" && ok "... starting with what changed, as comments" || bad "second summary"
out=$(migrate_db "$DB" "$P/db/migrations") && [ "$(PSQL -c "SET authz.user_id = 1" -c "SELECT authz.can('file', 11, 'comment')")" = t ] &&
  ok "it applies: the new permission is there" || bad "second applies" "$out"
out=$(PGOPTIONS="-c client_min_messages=error" psql -X -q -1 -v ON_ERROR_STOP=1 -d "$DB" -f "$second" 2>&1)
case "$out" in *"this database already holds what this migration brings"*"tell your migration tool it is applied [AZ607]"*) ok "the same migration again is refused: the database holds it already";; *) bad "guard" "$out";; esac
fresh "${DB}_2"
out=$(PGOPTIONS="-c client_min_messages=error" psql -X -q -1 -v ON_ERROR_STOP=1 -d "${DB}_2" -f "$second" 2>&1)
case "$out" in *"this migration changes the policy the migration before it left"*"none"*) ok "... and so is one without the migrations before it";; *) bad "guard on empty" "$out";; esac
# a lock_timeout the tool's session sets is kept (only none, 0, becomes 10 s)
out=$(PGOPTIONS="-c client_min_messages=error" psql -X -q -At -1 -v ON_ERROR_STOP=1 -d "${DB}_2" -c "SET LOCAL lock_timeout = '3s'" -f "$first" -c "SHOW lock_timeout" 2>&1)
[ "$(echo "$out" | tail -n 1)" = 3s ] && ok "a migration run with a lock_timeout of its tool's keeps it" || bad "lock_timeout in a migration" "$(echo "$out" | tail -n 3)"
echo "$first" >> "$T/applied_${DB}_2"
out=$(migrate_db "${DB}_2" "$P/db/migrations") && [ "$(PSQL -d "${DB}_2" -c "SELECT authz.verify()")" = t ] &&
  ok "a new database gets both, in order" || bad "both on a new database" "$out"

echo "-- rowstile push, for development databases"
sed -i 's/^  can comment = folder.view$/  can comment = folder.view\n  can print = view/' "$P/db/policy.authz"
out=$(CLI push 2>&1); rc=$?
case "$out" in *"isn't marked as a development database"*"[AZ610]"*"rowstile push --development"*) [ $rc -ne 0 ] &&
  ok "a database the migrations set up isn't pushed to until someone marks it as a development database" || bad "push rc" "$rc";;
  *) bad "push to an unmarked database" "$out";; esac
PSQL -c "INSERT INTO authz.settings VALUES ('development', 'false')" >/dev/null
out=$(CLI push 2>&1); rc=$?
case "$out" in *"isn't marked as a development database"*"[AZ610]"*) [ $rc -ne 0 ] &&
  ok "... nor while its mark says false" || bad "push with the mark false: rc" "$rc";;
  *) bad "push with the mark false" "$out";; esac
out=$(CLI push --development 2>&1); case "$out" in *"policy.authz: pushed") ok "push --development marks it, and brings it along with the migration it would write";; *) bad "push" "$out";; esac
[ "$(PSQL -c "SET authz.user_id = 1" -c "SELECT authz.can('file', 11, 'print')")" = t ] && ok "... the new permission is there" || bad "pushed permission"
out=$(CLI push 2>&1); case "$out" in *"policy.authz: unchanged") ok "push again: unchanged";; *) bad "push again" "$out";; esac
# rowstile push (rowstile dev, on each save), counting the policies it compiles and parses: the one in force once,
# and the new one once, only when its text changed
counted() { ( cd "$P" && python3 - "$OLDPWD" 2>&1 <<'PY'
import sys
sys.path[:0] = [sys.argv[1], sys.argv[1] + "/cli"]
import rowstile_cli
from authzlib import assembled, database
n = {"compiled": 0, "parsed": 0}
compile_, parse_ = assembled.Compiler.compile, database.parse_policy
def compile(self, *a, **k):
    n["compiled"] += 1
    return compile_(self, *a, **k)
def parse(*a, **k):
    n["parsed"] += 1
    return parse_(*a, **k)
assembled.Compiler.compile, database.parse_policy = compile, parse
try:
    rowstile_cli.main(["push"])
except SystemExit:
    pass
print(f"compiled {n['compiled']}, parsed {n['parsed']}")
PY
) | tail -n 2 | paste -sd ' '; }
out=$(counted); case "$out" in *"policy.authz: unchanged compiled 1, parsed 1") ok "... which compiles the policy in force once";; *) bad "push again, compiling" "$out";; esac
sed -i 's/^  can print = view$/  can print = edit/' "$P/db/policy.authz"
out=$(counted); case "$out" in *"policy.authz: pushed compiled 2, parsed 2") ok "a second change is pushed too, compiling the policy in force once and the new one once";; *) bad "second push" "$out";; esac
PSQL -c "UPDATE authz.policy_versions SET version = '0.0.1' WHERE id = (SELECT max(id) FROM authz.policy_versions)" >/dev/null
out=$(CLI push 2>&1); case "$out" in *"policy.authz: applied (the whole policy)") ok "a policy another version applied: the whole policy";; *) bad "push after upgrade" "$out";; esac
CLI migrate >/dev/null 2>&1
out=$(migrate_db "${DB}_2" "$P/db/migrations") && [ "$(PSQL -d "${DB}_2" -c "SELECT count(*) FROM authz_int.perms WHERE type = 'file' AND perm = 'print'")" = 1 ] &&
  ok "the migration for what was pushed applies to a database that took the migrations" || bad "migration after push" "$out $(ls "$P/db/migrations")"
out=$(PGOPTIONS="-c client_min_messages=error" psql -X -q -1 -v ON_ERROR_STOP=1 -d "$DB" -f "$(ls "$P"/db/migrations/*.sql | sort | tail -n 1)" 2>&1)
case "$out" in *"this database already holds what this migration brings"*"prisma migrate resolve --applied"*"alembic stamp head"*) ok "... but not to the pushed one, which holds it already: it says so, and what to tell the migration tool";; *) bad "guard after push" "$out";; esac
# something the policy in force made is gone (a rule's policy dropped by hand): push applies the whole policy, which
# makes it again, where the migration from what the record says would leave it out
PSQL -c "DROP POLICY authz_select ON app.files" >/dev/null
out=$(CLI push 2>&1)
case "$out" in *"policy.authz: applied (the whole policy)")
  [ "$(PSQL -c "SELECT count(*) FROM pg_policy WHERE polrelid = 'app.files'::regclass AND polname = 'authz_select'")" = 1 ] &&
  ok "push where a rule's policy was dropped by hand: the whole policy, which makes it again" || bad "push after a dropped policy: it is still gone";;
  *) bad "push after a dropped policy" "$out";; esac
# the policy on record changed by hand into text that doesn't compile (a stray line): it isn't the policy in force, so
# push applies the whole policy, and records it as it is
PSQL -c "UPDATE authz.policy_versions SET policy = policy || E'\nnonsense' WHERE id = (SELECT max(id) FROM authz.policy_versions)" >/dev/null
out=$(CLI push 2>&1); rc=$?
case "$out" in *"policy.authz: applied (the whole policy)")
  [ $rc -eq 0 ] && [ "$(PSQL -c "SELECT policy FROM authz.policy_versions ORDER BY id DESC LIMIT 1")" = "$(cat "$P/db/policy.authz")" ] &&
  ok "push where the policy on record was changed by hand into one that doesn't compile: the whole policy, recorded as it is" ||
  bad "push after the record was changed by hand: exit $rc, or the record";;
  *) bad "push after the record was changed by hand" "$out";; esac
# a user type's where that doesn't run: the migration that makes authz.uid() again reads it (Postgres would read it on
# the app's first query), and refuses it with its line, as applying the whole policy does (the user type without its
# permission, impersonate, whose view would read the where too)
cp "$P/db/policy.authz" "$T/keep.authz"
sed -i -e 's/^type user = app.users$/type user = app.users where {this.nme is not null}/' \
  -e '/^  -- support: an org admin/,/b.user_id = this.id)}$/d' "$P/db/policy.authz"
grep -q 'impersonate' "$P/db/policy.authz" && bad "the example's user type still has impersonate"
out=$(CLI push 2>&1); rc=$?
case "$out" in *"policy line $(grep -n '^type user = ' "$P/db/policy.authz" | cut -d: -f1): the condition {this.nme is not null} doesn't run: column u.nme does not exist [AZ613]"*)
  [ $rc -eq 1 ] && [ "$(PSQL -c "SELECT count(*) FROM pg_proc WHERE oid = 'authz.uid()'::regprocedure AND prosrc LIKE '%nme%'")" = 0 ] &&
  ok "push of a user type's where that doesn't run: refused with its line, authz.uid() as it was" || bad "push of a bad where: exit or state" "$rc";;
  *) bad "push of a user type's where that doesn't run" "$out";; esac
# one that runs when pushed, on a column only authz.uid() reads (no view holds it, so the app may drop it), which the
# app then drops (every query of the app fails): push of another change, apply and push of the same policy each read
# it again and refuse it with its line, where they said pushed or unchanged; the policy in force stays as it was
PSQL -c "ALTER TABLE app.users ADD COLUMN active boolean NOT NULL DEFAULT true" >/dev/null
sed -i -e 's/^type user = app.users where {this.nme is not null}$/type user = app.users where {active}/' "$P/db/policy.authz"
out=$(CLI push 2>&1) || bad "push of a user type's where on a column of its own" "$out"
PSQL -c "ALTER TABLE app.users DROP COLUMN active" >/dev/null
said="policy line $(grep -n '^type user = ' "$P/db/policy.authz" | cut -d: -f1): the condition {active} doesn't run: column \"active\" does not exist [AZ613]"
out=$(CLI push 2>&1); rc=$?
case "$out" in *"$said"*) [ $rc -eq 1 ] && [ "$(PSQL -c "SELECT policy FROM authz.policy_versions ORDER BY id DESC LIMIT 1")" = "$(cat "$P/db/policy.authz")" ] &&
  ok "a where on a column the app dropped since, push of the same policy: refused with its line, not unchanged" ||
  bad "push after a dropped column: exit or record" "$rc";;
  *) bad "push of the same policy after the app dropped a column a where reads" "$out";; esac
out=$(CLI apply 2>&1); rc=$?
case "$out" in *"$said"*) [ $rc -eq 1 ] && ok "... apply too: refused with its line, not unchanged" || bad "apply after a dropped column: exit" "$rc";;
  *) bad "apply after the app dropped a column a where reads" "$out";; esac
sed -i 's/^  can print = edit$/  can print = view/' "$P/db/policy.authz"
out=$(CLI push 2>&1); rc=$?
case "$out" in *"$said"*) [ $rc -eq 1 ] && [ "$(PSQL -c "SELECT policy LIKE '%can print = edit%' FROM authz.policy_versions ORDER BY id DESC LIMIT 1")" = t ] &&
  ok "... and the push of another change: refused with its line, nothing pushed" || bad "push of a change after a dropped column: exit or record" "$rc";;
  *) bad "push of another change after the app dropped a column a where reads" "$out";; esac
out=$(CLI apply --force 2>&1); rc=$?
case "$out" in *"$said"*) [ $rc -eq 1 ] && ok "... as applying the whole policy does" || bad "apply --force after a dropped column: exit" "$rc";;
  *) bad "apply --force after the app dropped a column a where reads" "$out";; esac
# the policy without that where: push applies it whole (the one in force isn't as it was), and the app's queries run
cp "$T/keep.authz" "$P/db/policy.authz"
out=$(CLI push 2>&1)
case "$out" in *"policy.authz: applied (the whole policy)") [ "$(PSQL -c "SELECT authz.uid() IS NULL")" = t ] &&
  ok "... until the policy reads it no more: applied whole, and authz.uid() runs" || bad "authz.uid() after the where went" "$out";;
  *) bad "push back to the policy without a where" "$out";; esac
# removing the policy doesn't make a database a development one: what it took is still on record
fresh "${DB}_4"
PGOPTIONS="-c client_min_messages=error" psql -X -q -1 -v ON_ERROR_STOP=1 -d "${DB}_4" -f "$first" >/dev/null 2>&1
out=$(CLI --db "dbname=${DB}_4" remove --yes 2>&1) || bad "remove on the migrated database" "$out"
out=$(CLI --db "dbname=${DB}_4" push 2>&1); rc=$?
case "$out" in *"had a policy (removed since) and isn't marked as a development database"*"[AZ610]"*) [ $rc -ne 0 ] &&
  [ "$(PSQL -d "${DB}_4" -c "SELECT count(*) FROM pg_namespace WHERE nspname = 'authz_int'")" = 0 ] &&
  ok "after rowstile remove, a database the migrations set up is still one push refuses" || bad "push after remove: rc or schemas" "$rc";;
  *) bad "push after remove" "$out";; esac
out=$(CLI --db "dbname=${DB}_4" push --development 2>&1)
case "$out" in *"policy.authz: applied (the whole policy)") ok "... until someone marks it: push --development";; *) bad "push --development after remove" "$out";; esac
out=$(CLI --db "dbname=${DB}_4" remove --yes 2>&1 && CLI --db "dbname=${DB}_4" push 2>&1)
case "$out" in *"policy.authz: applied (the whole policy)") ok "... and a marked one stays marked through remove";; *) bad "push after remove, marked" "$out";; esac

echo "-- an inheritance tree that changes: built beside the one in use, then swapped in"
sed -i 's/can view  = edit or viewer or (parent.view and {inherit})/can view  = edit or viewer or parent.view/' "$P/db/policy.authz"
before=$(ls "$P"/db/migrations/*.sql | wc -l)
out=$(CLI migrate 2>&1)
build=$(ls "$P"/db/migrations/*.sql | sort | tail -n 2 | head -n 1); swap=$(ls "$P"/db/migrations/*.sql | sort | tail -n 1)
case "$out" in *"beside the ones in use"*"two migrations"*) [ "$(ls "$P"/db/migrations/*.sql | wc -l)" = $((before + 2)) ] &&
  case "$build" in *_authz_build_*) true;; *) false;; esac && ok "migrate writes two: build beside, then swap in" || bad "two files" "$(ls "$P/db/migrations")";;
  *) bad "two-phase migrate" "$out";; esac
dropdb --if-exists "${DB}_5" 2>/dev/null; createdb --template "${DB}_2" "${DB}_5"   # (before the build: the oldest writer, below)
for n in 6 7 8 9; do dropdb --if-exists "${DB}_$n" 2>/dev/null; createdb --template "${DB}_2" "${DB}_$n"; done   # (and four more)
said=$(sed -n 3p "$build")
[ "$said" = "-- builds folder__linked_into_parent__tree beside the ones in use; the next migration swaps it in" ] &&
  ok "... the first says which tree it builds beside, and that the next swaps it in" || bad "the first's summary" "$said"
# the build holds its transaction open (until go) while the app writes
RACE_DB=${DB}_2 race
PGAPPNAME=authz_migrations_build PGOPTIONS="-c client_min_messages=error" psql -X -q -v ON_ERROR_STOP=1 -d "${DB}_2" -c "BEGIN" -f "$build" \
  -c "$HOLD" -c "COMMIT" 2> "$T/build.log" >/dev/null &
RACE_DB=${DB}_2 held authz_migrations_build
out=$(psql -X -q -At -d "${DB}_2" -c "SET lock_timeout = '1s'" -c "UPDATE app.folders SET name = name WHERE id = 4" \
          -c "INSERT INTO app.folder_links VALUES (6, 20)" 2>&1)
[ -z "$out" ] && ok "while the first one runs, the app still writes to the tables the tree follows" || bad "build blocks writers" "$out"
RACE_DB=${DB}_2 go; wait
[ ! -s "$T/build.log" ] && ok "... and it finishes" || bad "build" "$(cat "$T/build.log")"
echo "$build" >> "$T/applied_${DB}_2"
# a statement at a time (psql -f alone, which also goes on after an error): refused before anything changes, where
# the swap would stop half way with the old trees dropped
out=$(PGOPTIONS="-c client_min_messages=error" psql -X -q -d "${DB}_2" -f "$swap" 2>&1)
case "$out" in *"must run in one transaction"*"[AZ615]"*)
  [ "$(PSQL -d "${DB}_2" -c "SELECT authz.verify()")" = t ] &&
  [ "$(PSQL -d "${DB}_2" -c "SELECT count(*) FROM pg_proc WHERE proname = 'folder__linked_into_parent__tree_verify'")" = 1 ] &&
  [ "$(PSQL -d "${DB}_2" -c "SELECT count(*) FROM authz_int.next_trees")" -ge 1 ] &&
    ok "a migration run a statement at a time is refused (AZ615), and changes nothing" || bad "half a migration" "$(echo "$out" | head -n 5)";;
  *) bad "a migration outside a transaction" "$(echo "$out" | head -n 5)";; esac
out=$(migrate_db "${DB}_2" "$P/db/migrations") && [ "$(PSQL -d "${DB}_2" -c "SELECT authz.verify()")" = t ] &&
  [ "$(PSQL -d "${DB}_2" -c "SELECT count(*) FROM authz_int.folder__linked_into_parent__tree WHERE descendant = 6 AND ancestor = 20")" = 1 ] &&
  ok "the second swaps it in, with what the app wrote meanwhile" || bad "swap" "$out"
# a transaction that was the oldest one running when the build took its snapshot (its id is the snapshot's xmin)
# and that adds a link then commits: the swap does that link again. The build's snapshot is set to say so, as on a
# server where nothing older runs (here other databases' transactions may)
PGOPTIONS="-c client_min_messages=error" psql -X -q -1 -v ON_ERROR_STOP=1 -d "${DB}_5" -f "$build" >/dev/null 2>&1 ||
  bad "the build, on the copy"
x=$(PSQL -d "${DB}_5" -c "BEGIN" -c "INSERT INTO app.folder_links VALUES (6, 20)" -c "SELECT pg_current_xact_id()" -c "COMMIT")
PSQL -d "${DB}_5" -c "UPDATE authz_int.next_trees SET snap = '$x:$((x + 1)):$x'" >/dev/null
# (before its row, another tree's, whose snapshot came after that link: the swap reads its own row, by its name)
PSQL -d "${DB}_5" -c "CREATE TEMP TABLE mine AS SELECT * FROM authz_int.next_trees" -c "DELETE FROM authz_int.next_trees" \
  -c "INSERT INTO authz_int.next_trees SELECT * FROM mine" -c "UPDATE authz_int.next_trees SET name = 'another__tree', snap = '$((x + 1)):$((x + 1)):'" \
  -c "INSERT INTO authz_int.next_trees SELECT * FROM mine" >/dev/null
