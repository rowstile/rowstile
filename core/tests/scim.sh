-- what the app gives for the groups a provider makes, changes and deletes (the function the settings name): the
-- group's key in p_id (NULL: a new one), the group as SCIM writes it in p_resource (NULL: it is deleted)
CREATE FUNCTION sc.scim_group(p_id text, p_resource jsonb) RETURNS text LANGUAGE plpgsql AS \$f\$
DECLARE v_id text;
BEGIN
  IF p_resource->>'displayName' = 'retry' THEN
    RAISE EXCEPTION 'could not serialize access' USING ERRCODE = 'serialization_failure';
  ELSIF p_resource->>'displayName' = 'lost' THEN
    RETURN '999';
  ELSIF p_resource->>'displayName' = 'broken' THEN
    RETURN (SELECT no_such_column FROM sc.teams);
  ELSIF p_resource->>'displayName' ~ '^[a-z]' THEN
    RAISE EXCEPTION 'a team''s name starts with a capital letter';
  END IF;
  IF p_resource IS NULL THEN
    DELETE FROM sc.teams WHERE id = p_id::bigint;
    RETURN p_id;
  ELSIF p_id IS NULL THEN
    INSERT INTO sc.teams (name, scim_id) VALUES (p_resource->>'displayName', p_resource->>'externalId')
    RETURNING id::text INTO v_id;
  ELSE
    UPDATE sc.teams SET name = p_resource->>'displayName', scim_id = p_resource->>'externalId'
    WHERE id = p_id::bigint RETURNING id::text INTO v_id;
  END IF;
  RETURN v_id;
END \$f\$;
-- ... and for the users: it keeps the user as the provider wrote it (profile), and the name the app gave a user
-- the provider says no name of
CREATE FUNCTION sc.scim_user(p_id text, p_resource jsonb) RETURNS text LANGUAGE plpgsql AS \$f\$
DECLARE v_id text;
BEGIN
  IF p_resource IS NULL THEN
    DELETE FROM sc.users WHERE id = p_id::bigint;
    RETURN p_id;
  ELSIF p_id IS NULL THEN
    INSERT INTO sc.users (email, name, scim_id, active, profile)
    VALUES (p_resource->>'userName', coalesce(p_resource#>>'{name,formatted}', p_resource->>'displayName', p_resource->>'userName'),
            p_resource->>'externalId', coalesce((p_resource->>'active')::boolean, true), p_resource)
    RETURNING id::text INTO v_id;
  ELSE
    UPDATE sc.users SET email = p_resource->>'userName', scim_id = p_resource->>'externalId',
      name = coalesce(p_resource#>>'{name,formatted}', p_resource->>'displayName', name),
      active = coalesce((p_resource->>'active')::boolean, true), profile = p_resource
    WHERE id = p_id::bigint RETURNING id::text INTO v_id;
  END IF;
  RETURN v_id;
END \$f\$;
