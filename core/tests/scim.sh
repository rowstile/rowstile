ok() { echo "ok    $1"; }
bad() { echo "FAIL  $1: ${2:-}"; fails=$((fails + 1)); }
PSQL() { psql -X -q -At -v ON_ERROR_STOP=1 -d "$DB" "$@"; }
own() { PSQL -c "$1" 2>&1 | tail -n 1; }    # a question, asked as the owner
state() { psql -X -q -At -d "$DB" -c "SET ROLE app_user;" "$@" 2>&1 | tail -n 1; }
