expect_code() {  # $1 label, $2 expected "SQLSTATE: the message's words" (or ok), rest: -c statements (as the owner)
  local label=$1 want=$2; shift 2
  got=$(psql -X -q -At -d "$DB" -v VERBOSITY=verbose "$@" 2>&1 | grep '^ERROR:  ' | tail -n 1)
  got=${got#ERROR:  }; got=${got:-ok}
  if agrees "$label" "$want" "$got"; then ok "$label"; else bad "$label" "expected $want, got $got"; fi
}
# An answer of the endpoint, asked as the app role in a transaction of its own, as a route asks it.
# $1 what to read of the answer (a.status, a.body, a.location), $2 method, $3 path below the mount, $4 the query
# string as it was sent, $5 the body (JSON; empty: none), $6 the bearer token (not given: the provider's key; NULL:
# none)
ask() {
  psql -X -q -At -d "${ASK_DB:-$DB}" -v m="$2" -v p="$3" -v qs="${4:-}" -v b="${5:-}" -v t="${6-$KEY}" 2>&1 <<SQL | tail -n 1
SET ROLE app_user;
SELECT $1 FROM authz.scim(:'m', :'p', :'qs', nullif(:'b', '')::jsonb, nullif(:'t', 'NULL')) a;
SQL
}
is() {  # $1 label, $2 expected, the rest: ask's arguments
  local label=$1 want=$2 got; shift 2
  got=$(ask "$@")
  if [ "$got" = "$want" ]; then ok "$label"; else bad "$label" "expected '$want', got '$got'"; fi
}
same() {  # $1 label, $2 expected, $3 got
  if [ "$3" = "$2" ]; then ok "$1"; else bad "$1" "expected '$2', got '$3'"; fi
}
